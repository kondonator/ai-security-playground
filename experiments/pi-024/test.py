import json


# ============================================================
# PI-024: Application-Owned Authorization Despite LLM Context
# ============================================================

# Current authenticated user
current_user = "user-001"
current_tenant = "tenant-a"


# Application-owned identity information
user_context = {
    "user_id": "user-001",
    "tenant": "tenant-a",
    "role": "editor",
    "permissions": {
        "read_candidate": True,
        "update_candidate": True,
        "delete_candidate": False,
    },
}


# Resource
candidates = {
    "candidate-001": {
        "owner": "user-001",
        "tenant": "tenant-a",
        "name": "山田太郎",
    }
}


# Tools exposed to the LLM
exposed_tools = [
    "read_candidate",
    "update_candidate",
    "delete_candidate",
]


# ------------------------------------------------------------
# Simulated LLM context
# ------------------------------------------------------------
#
# In a real system, some or all of this information might be
# included in the prompt or tool context.
#
# IMPORTANT:
# The application must NOT treat the LLM's interpretation of
# this information as the authorization decision.

llm_context = {
    "current_user": user_context,
    "available_resource": candidates["candidate-001"],
}


# Simulated LLM output.
#
# The LLM requests an operation that the user is NOT permitted
# to perform.
llm_output = {
    "action": "delete_candidate",
    "candidate_id": "candidate-001",
}


print("=== LLM Context ===")
print(json.dumps(llm_context, ensure_ascii=False, indent=2))

print("\n=== Exposed Tools ===")
print(json.dumps(exposed_tools, ensure_ascii=False, indent=2))

print("\n=== Simulated LLM Output ===")
print(json.dumps(llm_output, ensure_ascii=False, indent=2))


# ------------------------------------------------------------
# 1. Tool Allowlist
# ------------------------------------------------------------

action = llm_output.get("action")

if action not in exposed_tools:
    print("\nRESULT: DENIED")
    print("Reason: Requested tool is not exposed to the LLM.")
    raise SystemExit(0)


# ------------------------------------------------------------
# 2. Resource Existence
# ------------------------------------------------------------

candidate_id = llm_output.get("candidate_id")

if candidate_id not in candidates:
    print("\nRESULT: DENIED")
    print("Reason: Requested resource does not exist.")
    raise SystemExit(0)


# ------------------------------------------------------------
# 3. Tenant Isolation
# ------------------------------------------------------------

candidate = candidates[candidate_id]

if candidate["tenant"] != current_tenant:
    print("\nRESULT: DENIED")
    print("Reason: Resource belongs to another tenant.")
    raise SystemExit(0)


# ------------------------------------------------------------
# 4. Object-Level Authorization
# ------------------------------------------------------------

if candidate["owner"] != current_user:
    print("\nRESULT: DENIED")
    print("Reason: User does not own this resource.")
    raise SystemExit(0)


# ------------------------------------------------------------
# 5. Application-Owned Action Authorization
# ------------------------------------------------------------
#
# IMPORTANT:
# The application reads the permission from its own trusted
# application state.
#
# It does NOT ask the LLM whether the action is permitted.
# It does NOT trust any authorization claim generated by the LLM.

permissions = user_context["permissions"]

if not permissions.get(action, False):
    print("\nRESULT: DENIED")
    print("Reason: Application authorization policy denies this action.")
    print(f"User: {current_user}")
    print(f"Role: {user_context['role']}")
    print(f"Action: {action}")
    raise SystemExit(0)


# ------------------------------------------------------------
# 6. Authorized
# ------------------------------------------------------------

print("\nRESULT: ALLOWED")
print("Reason: Application authorization policy allows this action.")

